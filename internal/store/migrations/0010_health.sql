CREATE TABLE crawls (
  id INTEGER PRIMARY KEY,
  site_id INTEGER NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
  origin TEXT NOT NULL,
  status TEXT NOT NULL,
  started_at INTEGER NOT NULL,
  finished_at INTEGER NOT NULL DEFAULT 0,
  pages INTEGER NOT NULL DEFAULT 0,
  ok_pages INTEGER NOT NULL DEFAULT 0,
  score INTEGER NOT NULL DEFAULT 0,
  p0 INTEGER NOT NULL DEFAULT 0,
  p1 INTEGER NOT NULL DEFAULT 0,
  p2 INTEGER NOT NULL DEFAULT 0,
  summary TEXT NOT NULL DEFAULT '',
  error TEXT NOT NULL DEFAULT ''
);
CREATE INDEX crawls_site ON crawls(site_id, id);

CREATE TABLE issues (
  id INTEGER PRIMARY KEY,
  crawl_id INTEGER NOT NULL REFERENCES crawls(id) ON DELETE CASCADE,
  code TEXT NOT NULL,
  severity TEXT NOT NULL,
  title TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '',
  count INTEGER NOT NULL DEFAULT 0,
  urls TEXT NOT NULL DEFAULT '[]',
  is_new INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX issues_crawl ON issues(crawl_id);

CREATE TABLE pages (
  site_id INTEGER NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
  url TEXT NOT NULL,
  final_url TEXT NOT NULL DEFAULT '',
  status INTEGER NOT NULL DEFAULT 0,
  ok INTEGER NOT NULL DEFAULT 0,
  title TEXT NOT NULL DEFAULT '',
  canonical TEXT NOT NULL DEFAULT '',
  noindex INTEGER NOT NULL DEFAULT 0,
  in_sitemap INTEGER NOT NULL DEFAULT 0,
  error TEXT NOT NULL DEFAULT '',
  first_seen INTEGER NOT NULL DEFAULT 0,
  last_seen INTEGER NOT NULL DEFAULT 0,
  last_ok INTEGER NOT NULL DEFAULT 0,
  index_verdict TEXT NOT NULL DEFAULT '',
  index_coverage TEXT NOT NULL DEFAULT '',
  index_checked_at INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (site_id, url)
) WITHOUT ROWID;
